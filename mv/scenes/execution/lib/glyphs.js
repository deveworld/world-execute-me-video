// 8x8 bitmap glyphs (rows top→bottom, '#' = lit) for the home-computer eras.
// C64: the uppercase/graphics character ROM. TOPAZ: Amiga Workbench 1.x topaz/8.

const parse = (src) => {
  const out = {};
  for (const [ch, rows] of Object.entries(src)) out[ch] = rows.split('|').map((r) => r.split('').map((c) => (c === '#' ? 1 : 0)));
  return out;
};

