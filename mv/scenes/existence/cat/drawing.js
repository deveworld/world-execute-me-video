export function createCatDrawing() {
  const frontSpeed = k => {
    const knots = [[0, 0], [.333, .401], [.458, .519], [.708, .770], [.833, .880], [1, 1]];
    for (let i = 1; i < knots.length; i++) if (k <= knots[i][0]) {
      const [a, x] = knots[i - 1], [b, y] = knots[i];
      return x + (y - x) * (k - a) / (b - a);
    }
    return 1;
  };
  const strokes = OUTLINE.map(([d, start, duration], i) => penStroke(d, {
    start, duration, width: 3.1, pressure: .05, ease: i === 1 ? frontSpeed : k => k,
  }));
  const tail = createTail();
  return { draw(ctx, t) {
    ctx.save(); ctx.fillStyle = '#16110f';
    for (const stroke of strokes) stroke.draw(ctx, t);
    tail(ctx, t);
    ctx.restore();
  } };
}
