// Draw `text` with an 8x8 bitmap font: cell (cw x ch) px at (x, y); pixels drawn as rects.
export function drawBitmapText(ctx, font, text, x, y, cw, ch, color) {
  ctx.fillStyle = color;
  const pw = cw / 8, ph = ch / 8;
  for (let i = 0; i < text.length; i++) {
    const g = font[text[i]];
    if (!g) continue;
    for (let r = 0; r < 8; r++) {
      const row = g[r];
      let c = 0;
      while (c < 8) {
        if (!row[c]) { c++; continue; }
        let e = c;
        while (e < 8 && row[e]) e++;
        ctx.fillRect(x + i * cw + c * pw, y + r * ph, (e - c) * pw, ph);
        c = e;
      }
    }
  }
}
